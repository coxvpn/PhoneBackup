    /** The province of an Iranian city by its name or, failing that, of the closest known city within [maxKm]; empty when unknown. */
    fun province(name: String, lat: Double?, lon: Double?, maxKm: Double = 60.0): String {
        PROVINCE[name.trim()]?.let { return it }
        if (lat == null || lon == null) return ""
        val near = name(lat, lon, maxKm)
        return PROVINCE[near] ?: ""
    }
