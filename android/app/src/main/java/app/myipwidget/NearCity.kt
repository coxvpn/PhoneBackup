    /** The name of the closest city within [maxKm], or empty. */
    fun name(lat: Double, lon: Double, maxKm: Double = 45.0): String {
        var best = ""
        var bestKm = Double.MAX_VALUE
        for ((n, la, lo) in CITIES) {
            val dLat = Math.toRadians(la - lat)
            val dLon = Math.toRadians(lo - lon)
            val h = Math.sin(dLat / 2).let { it * it } +
                Math.cos(Math.toRadians(lat)) * Math.cos(Math.toRadians(la)) * Math.sin(dLon / 2).let { it * it }
            val km = 12742.0 * Math.asin(Math.sqrt(h))
            if (km < bestKm) { bestKm = km; best = n }
        }
        return if (bestKm <= maxKm) best else ""
    }

